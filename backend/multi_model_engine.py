class TriageResponse(BaseModel):
    """
    Strict schema ensuring the LLM output matches Frontend UI sections.
    """
    model_config = ConfigDict(protected_namespaces=())

    reasoning: str = Field(
        ..., 
        description="Internal clinical thinking process. Analyze the provided symptoms and risk factors."
    )
    answer: str = Field(
        ..., 
        description="Direct answer to the user's question or the triage summary."
    )
    follow_up_questions: List[str] = Field(
        ..., 
        description="3 distinct follow-up questions to ask the patient.",
        min_items=1,
        max_items=5
    )

